/// Stream tag for per-hit random draws.
pub const DRUM_HIT: Tag = tag("drums.hit");
/// Stream tag of a voice's fixed draws (the same for every seed).
const DRUM_KIT: Tag = tag("instruments.drums.kit");
/// Stream tag of the per-seed draws of a voice's variants and of the swish.
const DRUM_VAR: Tag = tag("instruments.drums.variant");

/// Longest swish in seconds; longer (or non-finite) requests are clamped.
pub const MAX_SWISH: f64 = 4.0;
/// Shortest swish in seconds.
pub const MIN_SWISH: f64 = 0.02;
/// Variants per voice and layer.
pub const VARIANTS: usize = 4;

/// Lowest and highest mode, Hz.
const F_LO: f64 = 30.0;
const F_HI: f64 = 16000.0;
/// Mode spacing: the larger of this and `SPACING_REL f`, Hz; jitter +-45%.
const SPACING_MIN: f64 = 4.0;
const SPACING_REL: f64 = 0.015;
/// Mode length in decay time constants.
const MODE_TAUS: f64 = 7.0;
/// Weight of the fixed (per voice) draw in a variant's mode amplitude.
const KIT_WEIGHT: f64 = 0.9;
/// Shortest onset ramp, seconds.
const MIN_ATTACK: f64 = 0.0005;
/// Zero-sum DC pulse length, seconds.
const DC_PULSE: f64 = 0.005;
/// Final linear fade, seconds.
const END_FADE: f64 = 0.010;
/// Longest hit, seconds.
const MAX_LEN: f64 = 3.0;
/// Curve level above which a band counts for the hit length, dB.
const LEN_FLOOR_DB: f64 = -35.0;
/// Most a strong mode's power may take from its band (12 dB down), as a fraction.
const BAND_FLOOR: f64 = 0.063096;
/// The energy window of the reference statistics, seconds.
const STAT_WINDOW: f64 = 0.6;
/// The level window, seconds.
const LEVEL_WINDOW: f64 = 0.3;
/// Layer centres in velocity.
const CENTRES: [f64; 3] = [0.25, 0.6, 0.95];

/// Swish impulse response length, seconds, and decay time constant.
const SWISH_IR_SECS: f64 = 0.030;
const SWISH_TAU: f64 = 0.004;
/// Energy of the swish impulse response: the old voice's variance over the
/// stroke, `0.0279^2`, over the variance of the white input (1/3) and the mean
/// square of the envelope (0.30606).
const SWISH_IR_ENERGY: f64 = 0.0076299;
/// Overlap-add block and FFT length of the swish convolution.
const SWISH_BLOCK: usize = 2048;
const SWISH_FFT: usize = 4096;

/// The modal voices.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Voice {
    Kick,
    Snare,
    Rim,
    Tap,
    Hat,
    Tom,
    Ride,
}

impl Voice {
    fn code(self) -> u64 {
        self as u64
    }

    fn data(self) -> &'static VoiceData {
        match self {
            Voice::Kick => &data::KICK,
            Voice::Snare => &data::SNARE,
            Voice::Rim => &data::RIM,
            Voice::Tap => &data::TAP,
            Voice::Hat => &data::HAT,
            Voice::Tom => &data::TOM,
            Voice::Ride => &data::RIDE,
        }
    }

    /// Shortest hit, seconds: the length of the oscillator voice this model
    /// replaced.
    fn min_len(self) -> f64 {
        match self {
            Voice::Kick => 0.45,
            Voice::Snare => 0.3,
            Voice::Rim => 0.12,
            Voice::Tap => 0.25,
            Voice::Hat => 0.12,
            Voice::Tom => 0.5,
            Voice::Ride => 1.6,
        }
    }

    /// Impulse response length, seconds: 7 of the longest decay time
    /// constant among the octave bands whose curve is above -35 dB (any
    /// layer), at most 3 s and at least `min_len`.
    fn len_secs(self) -> f64 {
        let mut tau = 0.0f64;
        for l in &self.data().layers {
            for (i, &c) in OCT.iter().enumerate() {
                let j = BANDS.iter().position(|&b| b == c).unwrap_or(0);
                if l.curve[j] > LEN_FLOOR_DB {
                    tau = tau.max(l.tau[i]);
                }
            }
        }
        (MODE_TAUS * tau).min(MAX_LEN).max(self.min_len())
    }

    /// RMS over the first 0.3 s of the hard layer at unit velocity: that of
    /// the oscillator voice this model replaced (measured at velocity 0.95
    /// over 8 hits, divided by 0.95).
    fn ref_rms(self) -> f64 {
        match self {
            Voice::Kick => 0.3709,
            Voice::Snare => 0.1898,
            Voice::Rim => 0.06223,
            Voice::Tap => 0.1178,
            Voice::Hat => 0.07553,
            Voice::Tom => 0.4538,
            Voice::Ride => 0.05536,
        }
    }
}

/// The voice and tuning of a kind, `None` for the swish and the shaker.
fn voice_of(kind: DrumKind) -> Option<(Voice, f64)> {
    Some(match kind {
        DrumKind::Kick => (Voice::Kick, 0.0),
        DrumKind::Snare => (Voice::Snare, 0.0),
        DrumKind::Rim => (Voice::Rim, 0.0),
        DrumKind::Tap => (Voice::Tap, 0.0),
        DrumKind::Hat => (Voice::Hat, 0.0),
        DrumKind::Tom { hz } => (Voice::Tom, tom_hz(hz)),
        DrumKind::Ride => (Voice::Ride, 0.0),
        DrumKind::Swish { .. } | DrumKind::Shaker => return None,
    })
}

/// A voice's mode table: frequencies, spacings and the complex amplitude
/// draws of every variant (unit variance), the same for every layer.
struct Modes {
    f: Vec<f64>,
    df: Vec<f64>,
    /// `z[k][i]` = (re, im) of mode i in variant k.
    z: Vec<Vec<(f64, f64)>>,
    /// Unit phasors of the strong modes per variant.
    sz: Vec<[(f64, f64); 4]>,
}

impl Modes {
    fn new(voice: Voice, seed: u64) -> Modes {
        let mut kit = Rng::stream(voice.code(), DRUM_KIT);
        let mut var: Vec<Rng> = (0..VARIANTS)
            .map(|k| Rng::event(seed, DRUM_VAR, voice.code() * VARIANTS as u64 + k as u64))
            .collect();
        let (mut f, mut df, mut z) = (Vec::new(), Vec::new(), vec![Vec::new(); VARIANTS]);
        let mut fc = F_LO;
        let kw = KIT_WEIGHT;
        let vw = (1.0 - kw * kw).sqrt();
        loop {
            let step = (fc * SPACING_REL).max(SPACING_MIN) * (0.55 + 0.9 * kit.uniform());
            fc += step;
            if fc >= F_HI {
                break;
            }
            let (gk, pk) = (kit.gauss(), kit.uniform() * 2.0 * PI);
            for (zk, r) in z.iter_mut().zip(var.iter_mut()) {
                let (g, p) = (r.gauss(), r.uniform() * 2.0 * PI);
                zk.push((
                    kw * gk * pk.cos() + vw * g * p.cos(),
                    kw * gk * pk.sin() + vw * g * p.sin(),
                ));
            }
            f.push(fc);
            df.push(step);
        }
        let kp: Vec<f64> = (0..4).map(|_| kit.uniform() * 2.0 * PI).collect();
        let sz = var
            .iter_mut()
            .map(|r| {
                let mut a = [(1.0, 0.0); 4];
                for (s, &p) in a.iter_mut().zip(&kp) {
                    let q = r.uniform() * 2.0 * PI;
                    let (re, im) = (kw * p.cos() + vw * q.cos(), kw * p.sin() + vw * q.sin());
                    let m = re.hypot(im).max(1e-12);
                    *s = (re / m, im / m);
                }
                a
            })
            .collect();
        Modes { f, df, z, sz }
    }
}

/// Linear interpolation of `ys` over ln(`xs`), held beyond the ends.
fn interp_log(xs: &[f64], ys: &[f64], x: f64) -> f64 {
    let n = xs.len();
    if x <= xs[0] {
        return ys[0];
    }
    if x >= xs[n - 1] {
        return ys[n - 1];
    }
    let i = xs.partition_point(|&v| v <= x) - 1;
    let t = (x / xs[i]).ln() / (xs[i + 1] / xs[i]).ln();
    ys[i] + (ys[i + 1] - ys[i]) * t
}

/// Power density curve, dB per hertz up to a constant: the band curve less
/// 10 log10 of each band's width.
fn density_db(curve: &[f64; 28]) -> [f64; 28] {
    let mut d = [0.0; 28];
    let w = 2f64.powf(1.0 / 6.0) - 2f64.powf(-1.0 / 6.0);
    for (i, v) in d.iter_mut().enumerate() {
        *v = curve[i] - 10.0 * (BANDS[i] * w).log10();
    }
    d
}

/// Sum of `r^(2i) / 2` for i < min(m, window): the energy of `sin` times a
/// unit-amplitude decay over the statistics window.
fn mode_energy(r: f64, m: usize) -> f64 {
    let m = m.min((STAT_WINDOW * SR_F) as usize) as i32;
    let r2 = r * r;
    0.5 * (1.0 - r2.powi(m)) / (1.0 - r2)
}

/// One mode ready to run.
struct Run {
    w: f64,
    r: f64,
    m: usize,
    amp: f64,
}

/// Runs a mode with complex amplitude `c` (= a e^(j ph)) into `acc`.
fn add_mode(acc: &mut [f64], run: &Run, c: (f64, f64)) {
    let a = run.amp * c.0.hypot(c.1);
    let ph = c.1.atan2(c.0);
    let (cw, r) = (2.0 * run.r * run.w.cos(), run.r * run.r);
    let mut y1 = a * ph.sin();
    let mut y2 = a * (ph - run.w).sin() / run.r;
    let m = run.m.min(acc.len());
    for x in acc[..m].iter_mut() {
        *x += y1;
        let y = cw * y1 - r * y2;
        y2 = y1;
        y1 = y;
    }
}

/// Ramp, DC removal, fade and level of a raw impulse response; `level` is the
/// target RMS of its first 0.3 s.
fn finish(acc: &mut [f64], attack: f64, level: f64) -> Vec<f32> {
    let n = acc.len();
    let na = ((attack.max(MIN_ATTACK)) * SR_F).round() as usize;
    for (i, x) in acc.iter_mut().take(na).enumerate() {
        *x *= 0.5 * (1.0 - (PI * i as f64 / na as f64).cos());
    }
    let sum: f64 = acc.iter().sum();
    let lh = ((DC_PULSE * SR_F).round() as usize).min(n);
    for (i, x) in acc.iter_mut().take(lh).enumerate() {
        *x -= sum * (1.0 - (2.0 * PI * i as f64 / lh as f64).cos()) / lh as f64;
    }
    let nf = ((END_FADE * SR_F).round() as usize).min(n);
    for i in 0..nf {
        acc[n - 1 - i] *= (i as f64 + 0.5) / nf as f64;
    }
    let w = ((LEVEL_WINDOW * SR_F) as usize).min(n);
    let e: f64 = acc[..w].iter().map(|x| x * x).sum::<f64>() / (LEVEL_WINDOW * SR_F);
    let g = if e > 0.0 { level / e.sqrt() } else { 0.0 };
    acc.iter().map(|&x| (x * g) as f32).collect()
}

/// The `VARIANTS` impulse responses of one layer of a voice; `shift` moves
/// the curve and the strong modes along the frequency axis (the tom).
fn build_layer(voice: Voice, modes: &Modes, li: usize, shift: f64) -> Vec<Vec<f32>> {
    let vd = voice.data();
    let layer: &Layer = &vd.layers[li];
    let n = (voice.len_secs() * SR_F).round() as usize;
    // The curve holds the strong modes' energy: take their power from the
    // band that contains each (at most down to 12 dB under the band).
    let mut curve = layer.curve;
    let mut power: Vec<f64> = curve.iter().map(|d| 10f64.powf(d / 10.0)).collect();
    let orig = power.clone();
    for sm in vd.modes {
        let w = 2f64.powf(1.0 / 6.0);
        if let Some(b) = BANDS.iter().position(|&c| sm.f >= c / w && sm.f < c * w) {
            power[b] = (power[b] - 10f64.powf(sm.db / 10.0)).max(orig[b] * BAND_FLOOR);
        }
    }
    for (c, p) in curve.iter_mut().zip(&power) {
        *c = 10.0 * p.log10();
    }
    let dens = density_db(&curve);
    let ln_tau: Vec<f64> = layer.tau.iter().map(|t| t.max(1e-4).ln()).collect();
    let mut runs: Vec<Run> = Vec::with_capacity(modes.f.len() + 4);
    let mut e0 = 0.0;
    for (&f, &df) in modes.f.iter().zip(&modes.df) {
        let t = 10f64.powf(interp_log(&BANDS, &dens, f / shift) / 10.0);
        let tau = interp_log(&OCT, &ln_tau, f).exp();
        let r = (-1.0 / (tau * SR_F)).exp();
        let m = n.min((tau * SR_F * MODE_TAUS).ceil() as usize);
        let amp = (t * df / tau).sqrt();
        e0 += amp * amp * mode_energy(r, m);
        runs.push(Run {
            w: 2.0 * PI * f / SR_F,
            r,
            m,
            amp,
        });
    }
    // Strong modes: energy p of the total, so p / (1 - sum p) of the rest.
    let strong: &[StrongMode] = vd.modes;
    let ps: Vec<f64> = strong.iter().map(|s| 10f64.powf(s.db / 10.0)).collect();
    let psum: f64 = ps.iter().sum::<f64>().min(0.9);
    let mut s_runs = Vec::new();
    for (si, (s, p)) in strong.iter().zip(&ps).enumerate() {
        let f = s.f * shift;
        if f >= 0.45 * SR_F {
            continue;
        }
        let tau = s.tau.max(1e-3);
        let r = (-1.0 / (tau * SR_F)).exp();
        let m = n.min((tau * SR_F * MODE_TAUS).ceil() as usize);
        let amp = (p / (1.0 - psum) * e0 / mode_energy(r, m)).sqrt();
        s_runs.push((
            si,
            Run {
                w: 2.0 * PI * f / SR_F,
                r,
                m,
                amp,
            },
        ));
    }
    let level = 10f64.powf(layer.level_db / 20.0) * voice.ref_rms();
    let mut acc = vec![0.0f64; n];
    (0..VARIANTS)
        .map(|k| {
            acc.iter_mut().for_each(|x| *x = 0.0);
            for (run, &z) in runs.iter().zip(&modes.z[k]) {
                add_mode(&mut acc, run, z);
            }
            for (i, run) in &s_runs {
                add_mode(&mut acc, run, modes.sz[k][*i]);
            }
            finish(&mut acc, layer.attack, level)
        })
        .collect()
}

/// The pools of one modal voice (and tuning): its mode table, the layers
/// built so far and the variant the previous hit used.
struct Pool {
    voice: Voice,
    /// Tom tuning as `f32` bits (0 for the others).
    tune: u32,
    shift: f64,
    modes: Modes,
    layers: [Option<Vec<Vec<f32>>>; 3],
    last: Option<usize>,
}

/// The swish's shaping filter: its impulse response spectrum and the FFT
/// buffers of the overlap-add.
struct SwishKit {
    fft: RealFft,
    spec: Vec<C32>,
    sp: Vec<C32>,
    fs: Vec<C32>,
    blk: Vec<f32>,
    out: Vec<f32>,
}

impl SwishKit {
    fn new(seed: u64) -> SwishKit {
        let n = (SWISH_IR_SECS * SR_F).round() as usize;
        let mut rng = Rng::event(seed, DRUM_VAR, 1000);
        let dens = density_db(&SWISH_CURVE);
        let r = (-1.0 / (SWISH_TAU * SR_F)).exp();
        let mut acc = vec![0.0f64; n];
        let mut f = F_LO;
        loop {
            let step = (f * SPACING_REL).max(SPACING_MIN) * (0.55 + 0.9 * rng.uniform());
            f += step;
            if f >= F_HI {
                break;
            }
            let t = 10f64.powf(interp_log(&BANDS, &dens, f) / 10.0);
            let run = Run {
                w: 2.0 * PI * f / SR_F,
                r,
                m: n,
                amp: (t * step / SWISH_TAU).sqrt(),
            };
            let (g, p) = (rng.gauss(), rng.uniform() * 2.0 * PI);
            add_mode(&mut acc, &run, (g * p.cos(), g * p.sin()));
        }
        let na = (MIN_ATTACK * SR_F).round() as usize;
        for (i, x) in acc.iter_mut().take(na).enumerate() {
            *x *= 0.5 * (1.0 - (PI * i as f64 / na as f64).cos());
        }
        let e: f64 = acc.iter().map(|x| x * x).sum();
        let g = (SWISH_IR_ENERGY / e.max(1e-300)).sqrt() / SWISH_FFT as f64;
        let mut ir = vec![0.0f32; SWISH_FFT];
        for (d, s) in ir.iter_mut().zip(&acc) {
            *d = (s * g) as f32;
        }
        let fft = RealFft::new(SWISH_FFT);
        let mut fs = fft.make_scratch();
        let mut spec = vec![C32::new(0.0, 0.0); fft.spectrum_len()];
        fft.forward(&mut ir, &mut spec, &mut fs).expect("fft sizes");
        SwishKit {
            sp: vec![C32::new(0.0, 0.0); fft.spectrum_len()],
            blk: vec![0.0; SWISH_FFT],
            out: vec![0.0; SWISH_FFT],
            fft,
            spec,
            fs,
        }
    }

    /// `out[..n]` = `x[..n]` convolved with the impulse response (the first
    /// n samples of the full convolution).
    fn convolve(&mut self, x: &[f32], out: &mut [f32]) {
        out.iter_mut().for_each(|v| *v = 0.0);
        let n = out.len();
        let mut start = 0;
        while start < n {
            let len = SWISH_BLOCK.min(n - start);
            self.blk[..len].copy_from_slice(&x[start..start + len]);
            self.blk[len..].iter_mut().for_each(|v| *v = 0.0);
            self.fft
                .forward(&mut self.blk, &mut self.sp, &mut self.fs)
                .expect("fft sizes");
            for (a, b) in self.sp.iter_mut().zip(&self.spec) {
                *a *= *b;
            }
            self.fft
                .inverse_unscaled(&mut self.sp, &mut self.out, &mut self.fs)
                .expect("fft sizes");
            let m = SWISH_FFT.min(n - start);
            for (o, v) in out[start..start + m].iter_mut().zip(&self.out) {
                *o += *v;
            }
            start += SWISH_BLOCK;
        }
    }
}

/// Reusable state of a render: the song seed, the mono voice and noise
/// buffers (they grow to the longest voice and are then reused), the impulse
/// response pools (built when a hit first needs them) and the swish filter.
pub struct DrumScratch {
    seed: u64,
    mono: Vec<f32>,
    n0: Vec<f32>,
    pools: Vec<Pool>,
    swish: Option<SwishKit>,
    /// Seconds spent building pools and the swish filter.
    build_secs: f64,
}

impl DrumScratch {
    /// Scratch for a render of the song seeded `seed`.
    pub fn new(seed: u64) -> Self {
        DrumScratch {
            seed,
            mono: Vec::new(),
            n0: Vec::new(),
            pools: Vec::new(),
            swish: None,
            build_secs: 0.0,
        }
    }

    /// Seconds spent so far building pools (diagnostics).
    pub fn build_secs(&self) -> f64 {
        self.build_secs
    }

    fn ensure(&mut self, n: usize) {
        for v in [&mut self.mono, &mut self.n0] {
            if v.len() < n {
                v.resize(n, 0.0);
            }
        }
    }

    /// Index of the pool of (`voice`, `hz`), created when absent.
    fn pool(&mut self, voice: Voice, hz: f64) -> usize {
        let tune = if voice == Voice::Tom {
            (hz as f32).to_bits()
        } else {
            0
        };
        if let Some(i) = self
            .pools
            .iter()
            .position(|p| p.voice == voice && p.tune == tune)
        {
            return i;
        }
        let t0 = Instant::now();
        // Toms of every tuning share one mode table: one drum, retuned.
        let modes = match self.pools.iter().position(|p| p.voice == voice) {
            Some(i) => Modes {
                f: self.pools[i].modes.f.clone(),
                df: self.pools[i].modes.df.clone(),
                z: self.pools[i].modes.z.clone(),
                sz: self.pools[i].modes.sz.clone(),
            },
            None => Modes::new(voice, self.seed),
        };
        self.pools.push(Pool {
            voice,
            tune,
            shift: if voice == Voice::Tom {
                hz / TOM_F0
            } else {
                1.0
            },
            modes,
            layers: [None, None, None],
            last: None,
        });
        self.build_secs += t0.elapsed().as_secs_f64();
        self.pools.len() - 1
    }

    /// Builds layer `li` of pool `pi` when absent.
    fn layer(&mut self, pi: usize, li: usize) {
        if self.pools[pi].layers[li].is_none() {
            let t0 = Instant::now();
            let p = &self.pools[pi];
            let built = build_layer(p.voice, &p.modes, li, p.shift);
            self.pools[pi].layers[li] = Some(built);
            self.build_secs += t0.elapsed().as_secs_f64();
        }
    }
}

/// Recursive exponential decay `exp(-t / tau)`, one multiply per sample.
#[derive(Clone, Copy)]
struct Decay {
    e: f64,
    r: f64,
}

impl Decay {
    fn new(tau: f64) -> Self {
        Decay {
            e: 1.0,
            r: (-1.0 / (tau * SR_F)).exp(),
        }
    }

    /// Current value, then advance.
    #[inline(always)]
    fn next(&mut self) -> f64 {
        let v = self.e;
        self.e *= self.r;
        v
    }
}

/// Linear attack `min(1, t / t_att)`.
#[derive(Clone, Copy)]
struct Attack {
    a: f64,
    inc: f64,
}

impl Attack {
    fn new(t_att: f64) -> Self {
        Attack {
            a: 0.0,
            inc: 1.0 / (t_att * SR_F),
        }
    }

    #[inline(always)]
    fn next(&mut self) -> f64 {
        let v = self.a;
        self.a = (self.a + self.inc).min(1.0);
        v
    }
}

fn secs(t: f64) -> usize {
    (t * SR_F).round() as usize
}

fn filter(buf: &mut [f32], c: BiquadCoeffs) {
    Biquad::new(c).process(buf);
}

fn bp(f: f64, q: f64) -> BiquadCoeffs {
    BiquadCoeffs::bandpass(SR_F, f, q)
}

/// Length in samples of a voice.
pub fn hit_len(kind: DrumKind) -> usize {
    match kind {
        DrumKind::Swish { dur } => secs(swish_dur(dur)),
        DrumKind::Shaker => secs(0.12),
        _ => match voice_of(kind) {
            Some((v, _)) => secs(v.len_secs()),
            None => 0,
        },
    }
}

fn swish_dur(dur: f32) -> f64 {
    let d = dur as f64;
    if d.is_finite() && d > 0.0 {
        d.clamp(MIN_SWISH, MAX_SWISH)
    } else {
        0.5
    }
}

fn tom_hz(hz: f32) -> f64 {
    let f = hz as f64;
    if f.is_finite() && f > 0.0 {
        f.clamp(20.0, 2000.0)
    } else {
        110.0
    }
}

/// The two layers around velocity `v` and the weight of the upper one.
fn layer_blend(v: f64) -> (usize, f64) {
    let v = if v.is_finite() { v } else { 0.0 };
    if v <= CENTRES[0] {
        return (0, 0.0);
    }
    if v >= CENTRES[2] {
        return (2, 0.0);
    }
    let i = if v < CENTRES[1] { 0 } else { 1 };
    (i, (v - CENTRES[i]) / (CENTRES[i + 1] - CENTRES[i]))
}

/// A variant of `VARIANTS`, never `last`: one draw, over the others.
fn pick_variant(last: Option<usize>, rng: &mut Rng) -> usize {
    match last {
        Some(l) => {
            let j = rng.below(VARIANTS as u32 - 1) as usize;
            j + usize::from(j >= l)
        }
        None => rng.below(VARIANTS as u32) as usize,
    }
}

/// Synthesise one voice at unit velocity into `s.mono[..n]`; returns n.
/// `vel` picks the layers of the modal voices.
fn synth(kind: DrumKind, vel: f64, rng: &mut Rng, s: &mut DrumScratch) -> usize {
    let n = hit_len(kind);
    s.ensure(n);
    if let Some((voice, hz)) = voice_of(kind) {
        let pi = s.pool(voice, hz);
        let (lo, w) = layer_blend(vel);
        s.layer(pi, lo);
        if w > 0.0 {
            s.layer(pi, lo + 1);
        }
        // One draw, made last: a variant other than the previous hit's.
        let pool = &mut s.pools[pi];
        let k = pick_variant(pool.last, rng);
        pool.last = Some(k);
        let a = &pool.layers[lo].as_ref().expect("layer built")[k];
        let out = &mut s.mono[..n];
        if w > 0.0 {
            let b = &pool.layers[lo + 1].as_ref().expect("layer built")[k];
            let (wa, wb) = ((1.0 - w) as f32, w as f32);
            for ((o, x), y) in out.iter_mut().zip(a).zip(b) {
                *o = wa * x + wb * y;
            }
        } else {
            out.copy_from_slice(&a[..n]);
        }
        return n;
    }
    let DrumScratch {
        mono,
        n0,
        swish,
        seed,
        build_secs,
        ..
    } = s;
    let out = &mut mono[..n];
    match kind {
        DrumKind::Swish { .. } => {
            let nz = &mut n0[..n];
            rng.fill_bipolar(nz);
            // sin(pi x), x = i / n, as a rotating phasor (exact angle
            // increment); sin(2 pi x) = 2 sin(pi x) cos(pi x).
            let w = PI / n as f64;
            let (rc, rs) = (w.cos(), w.sin());
            let (mut c, mut sn) = (1.0f64, 0.0f64);
            for z in nz.iter_mut() {
                let s1 = sn.max(0.0);
                let e = s1 * s1.sqrt() * (0.6 + 0.4 * (2.0 * sn * c).abs());
                *z = (*z as f64 * e) as f32;
                let c2 = c * rc - sn * rs;
                sn = sn * rc + c * rs;
                c = c2;
            }
            if swish.is_none() {
                let t0 = Instant::now();
                *swish = Some(SwishKit::new(*seed));
                *build_secs += t0.elapsed().as_secs_f64();
            }
            if let Some(k) = swish.as_mut() {
                k.convolve(nz, out);
            }
        }
        _ => {
            // Shaker.
            rng.fill_bipolar(out);
            filter(out, bp(6200.0, 1.3));
            let (mut a, mut e) = (Attack::new(0.012), Decay::new(0.045));
            for v in out.iter_mut() {
                *v = (*v as f64 * 1.4 * a.next() * e.next()) as f32;
            }
        }
    }
    n
}

/// Render one hit into the stereo stem: synthesise the voice, scale by
/// `hit.vel`, pan with equal-power gains and add at `sample_at(hit.t)`.
/// Samples outside the stem are dropped. A non-finite velocity renders
/// nothing.
pub fn render_hit(
    hit: &DrumHit,
    rng: &mut Rng,
    out_l: &mut [f32],
    out_r: &mut [f32],
    scratch: &mut DrumScratch,
) {
    let vel = hit.vel;
    if !vel.is_finite() || vel == 0.0 || !hit.t.is_finite() {
        return;
    }
    let n = synth(hit.kind, vel as f64, rng, scratch);
    let [gl, gr] = equal_power(hit.pan as f64);
    add_mono(
        out_l,
        out_r,
        sample_at(hit.t),
        &scratch.mono[..n],
        [gl * vel, gr * vel],
    );
}

/// Render all hits into a stereo stem of `len` samples. Hit k draws from
/// `Rng::event(seed, DRUM_HIT, k)`, so each hit's draws are independent of
/// the others.
pub fn render_drums(hits: &[DrumHit], seed: u64, len: usize) -> [Vec<f32>; 2] {
    let mut l = vec![0.0f32; len];
    let mut r = vec![0.0f32; len];
    let mut scratch = DrumScratch::new(seed);
    for (k, hit) in hits.iter().enumerate() {
        let mut rng = Rng::event(seed, DRUM_HIT, k as u64);
        render_hit(hit, &mut rng, &mut l, &mut r, &mut scratch);
    }
    [l, r]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_variant_never_repeats_and_all_others_occur() {
        let mut rng = Rng::from_seed(5);
        for last in 0..VARIANTS {
            let mut seen = [0usize; VARIANTS];
            for _ in 0..4000 {
                seen[pick_variant(Some(last), &mut rng)] += 1;
            }
            assert_eq!(seen[last], 0, "variant {last} repeated");
            assert!(seen.iter().enumerate().all(|(k, &c)| k == last || c > 1000));
        }
        let first: Vec<usize> = (0..400).map(|_| pick_variant(None, &mut rng)).collect();
        assert!((0..VARIANTS).all(|k| first.contains(&k)));
    }

    #[test]
    fn layer_blend_runs_between_centres() {
        assert_eq!(layer_blend(0.1), (0, 0.0));
        assert_eq!(layer_blend(0.25), (0, 0.0));
        assert_eq!(layer_blend(0.6), (1, 0.0));
        assert_eq!(layer_blend(0.95), (2, 0.0));
        assert_eq!(layer_blend(1.4), (2, 0.0));
        let (i, w) = layer_blend(0.775);
        assert_eq!(i, 1);
        assert!((w - 0.5).abs() < 1e-12);
        let (i, w) = layer_blend(0.425);
        assert_eq!(i, 0);
        assert!((w - 0.5).abs() < 1e-12);
    }
}
