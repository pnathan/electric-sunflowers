//! Drum voices: kick, snare, rim, brush tap and swish, hat, shaker, tom and
//! ride, rendered in place into a stereo stem (design section 5.8).
//!
//! A hit is a pooled impulse response scaled by the hit velocity and added at
//! `sample_at(hit.t)` with equal-power pan gains (`dsp::pan::equal_power`).
//! The blend of two velocity layers goes into a mono scratch buffer (reused
//! across hits, no per-hit allocation once it has grown to the longest voice).
//!
//! Model (Kick, Snare, Rim, Tap, Hat, Tom, Ride). Every drum is a dense set
//! of decaying modes with a broad spectrum, and the data are statistics of a
//! real acoustic kit (DRSKit 2.1, CC BY 4.0; `drum_data`, generated by
//! tools/drum_target.py). A hit is a stochastic modal impulse response, as in
//! `body` but with a decay time per frequency and no curve fit loop:
//! - Modes from 30 Hz to 16 kHz, spaced `max(4 Hz, 1.5% f)` with a uniform
//!   jitter of +-45% of the spacing. A mode at f is `a r^i sin(w i + ph)`,
//!   `r = exp(-1 / (tau fs))`, run by the recursive oscillator
//!   `y = 2 r cos(w) y1 - r^2 y2`, cut at 7 tau.
//! - `tau(f)`: the voice's octave-band decay table (amplitude time constants),
//!   interpolated in log tau over log f, held beyond 63 Hz and 16 kHz.
//! - Amplitude `a = sqrt(T(f) df / tau(f)) |z|`: `T` the band curve's power
//!   density (the 1/3-octave curve in dB less 10 log10 of the band width,
//!   interpolated in dB over log f, held beyond the end bands), `df` the
//!   mode's own spacing, and `z = g e^(j ph)` a complex amplitude, g standard
//!   normal, ph uniform.
//! - The voice's strong modes (medium layer data) are added with their
//!   level (energy against the hit's total) and tau; their amplitude is not
//!   random, their phase is. The band curve already holds their energy, so
//!   before the random modes are drawn each strong mode's power is taken from
//!   the 1/3-octave band that contains it (at most to 12 dB under the band).
//! - Onset: a raised-cosine ramp of the layer's attack time (at least
//!   0.5 ms), then the DC is removed with a zero-sum 5 ms pulse. The last
//!   10 ms fade out linearly. Each variant is scaled so that its RMS over the first
//!   0.3 s is the layer's level against the hard layer, times the hard layer's
//!   RMS (`REF_RMS`, the first-0.3-s RMS of the unit-velocity voice this
//!   model replaced, which keeps the kit's balance in the mix).
//! - Tom `hz`: the curve and the strong modes move along the frequency axis
//!   by `hz / TOM_F0` (the reference tom's fundamental); the decay table
//!   stays at its absolute frequencies.
//!
//! Velocity layers. Three layers (soft, medium, hard) have their own curve,
//! decay table, level and attack. A hit at velocity v blends the two layers
//! around it linearly in amplitude, layer centres at v = 0.25, 0.6, 0.95
//! (clamped at the ends), and is scaled by v.
//!
//! Variants. Per voice and layer there are `VARIANTS` (4) impulse responses.
//! The modes' frequencies come from a fixed stream per voice. A mode's
//! complex amplitude in variant k is `0.9 z_kit + sqrt(1 - 0.81) z_k`: `z_kit`
//! from the voice's fixed stream (the same for every seed, as the fixed low
//! modes of a body, so a voice keeps its identity), `z_k` from the seed. The
//! draws do not depend on the layer, so the layers of a variant are coherent
//! and a blend of two is a morph, not a sum of two unrelated hits. A hit
//! takes its variant from its own event stream (one draw, made last) and
//! never the variant that the previous hit of its voice used.
//!
//! Pools are built once per render, lazily per voice and layer, when a hit
//! first needs them (`DrumScratch`, which also holds the seed).
//!
//! Swish (sustained): white noise times the envelope `sin(pi x)^1.5 (0.6 +
//! 0.4 |sin(2 pi x)|)` over x in [0, 1) (the swell, and the stroke
//! modulation of the swirl), convolved (FFT overlap-add) with a 30 ms
//! stochastic modal impulse response built from the swish curve, tau 4 ms for
//! every mode, normalised to the old voice's RMS over the stroke.
//!
//! Shaker: noise band-passed 6.2 kHz Q 1.3 x 1.4, 12 ms attack, decay
//! 0.045 s, unchanged (no reference).
//!
//! Building blocks of the shaker: the exponential envelope is recursive
//! (`e *= exp(-1 / (tau fs))`), the noise is `Rng::fill_bipolar` filtered
//! with `dsp::biquad` (RBJ cookbook designs).

